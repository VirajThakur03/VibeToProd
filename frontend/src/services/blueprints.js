const CUSTOM_BLUEPRINTS_KEY = 'ai_slice_custom_blueprints_v6';

const SYSTEM_BLUEPRINTS_MAP = {};
PRODUCTION_COMMANDS.forEach(cmd => {
  let promptContent = cmd.systemPrompt;
  if (cmd.name === '/professional') promptContent = PROFESSIONAL_MD_CONTENT;
  if (cmd.name === '/sec-audit') promptContent = SEC_AUDIT_MD_CONTENT;
  if (cmd.name === '/ui') promptContent = UI_MD_CONTENT;
  if (cmd.name === '/api') promptContent = API_MD_CONTENT;
  if (cmd.name === '/error') promptContent = ERROR_MD_CONTENT;
  if (cmd.name === '/plan') promptContent = PLAN_MD_CONTENT;

  SYSTEM_BLUEPRINTS_MAP[cmd.name.toLowerCase()] = {
    name: cmd.name,
    category: cmd.category,
    description: cmd.description,
    maxTokens: cmd.maxTokens,
    systemPrompt: promptContent
  };
});

export const SYSTEM_BLUEPRINTS = SYSTEM_BLUEPRINTS_MAP;

export function getAvailableBlueprints() {
  try {
    const customRaw = localStorage.getItem(CUSTOM_BLUEPRINTS_KEY);
    if (customRaw) {
      const custom = JSON.parse(customRaw);
      return { ...SYSTEM_BLUEPRINTS_MAP, ...custom };
    }
  } catch (e) {}
  return SYSTEM_BLUEPRINTS_MAP;
}

export function saveCustomBlueprint(commandName, description, systemPrompt, maxTokens = 400, category = 'Custom') {
  try {
    const cmd = commandName.startsWith('/') ? commandName.toLowerCase() : `/${commandName.toLowerCase()}`;
    const all = getAvailableBlueprints();
    
    all[cmd] = {
      name: cmd,
      category: category,
      description: description || `Custom blueprint for ${cmd}`,
      maxTokens: parseInt(maxTokens, 10) || 400,
      systemPrompt: systemPrompt
    };

    localStorage.setItem(CUSTOM_BLUEPRINTS_KEY, JSON.stringify(all));
    return all[cmd];
  } catch (e) {
    console.error("Failed to save blueprint", e);
    return null;
  }
}

export function wrapPromptClient(rawInput) {
  const trimmed = (rawInput || '').trim();
  const match = trimmed.match(/^(\/[\w\-]+)\s*(.*)/s);
  let cmd = '/plan';
  let query = trimmed;

  if (match) {
    cmd = match[1].toLowerCase();
    query = match[2].trim() || trimmed;
  }

  const allBlueprints = getAvailableBlueprints();
  const blueprint = allBlueprints[cmd] || SYSTEM_BLUEPRINTS_MAP['/plan'];

  return {
    commandUsed: cmd,
    userQuery: query,
    systemPrompt: blueprint.systemPrompt,
    userPrompt: query,
    maxTokens: blueprint.maxTokens,
    description: blueprint.description
  };
}
